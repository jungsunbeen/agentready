import type { Finding, Report, Rule } from './types.js';

export interface TextOptions {
  /** Emit ANSI colors. Callers decide based on TTY and NO_COLOR. */
  readonly color: boolean;
}

const ANSI = { red: 31, green: 32, yellow: 33, dim: 2 } as const;
type AnsiColor = keyof typeof ANSI;

function painter(enabled: boolean) {
  return (color: AnsiColor, text: string): string => (enabled ? `\u001b[${String(ANSI[color])}m${text}\u001b[0m` : text);
}

function icon(finding: Finding, paint: ReturnType<typeof painter>): string {
  switch (finding.status) {
    case 'pass':
      return paint('green', '✔');
    case 'skip':
      return paint('dim', '-');
    case 'fail':
      return finding.severity === 'error' ? paint('red', '✖') : paint('yellow', '!');
  }
}

export function formatText(report: Report, options: TextOptions): string {
  const paint = painter(options.color);
  const width = Math.max(0, ...report.findings.map((finding) => finding.ruleId.length));
  const lines: string[] = [];

  for (const finding of report.findings) {
    lines.push(`${icon(finding, paint)} ${finding.ruleId.padEnd(width)}  ${finding.message}`);
    if (finding.status === 'fail' && finding.fix !== undefined) {
      lines.push(`  ${' '.repeat(width)}  ${paint('dim', `→ ${finding.fix}`)}`);
    }
  }

  const { pass, fail, skip } = report.summary;
  lines.push(
    '',
    `Score ${String(report.score)}/100 · ${String(pass)} passed, ${String(fail)} failed, ${String(skip)} skipped`,
  );
  return `${lines.join('\n')}\n`;
}

export function formatJson(report: Report): string {
  return `${JSON.stringify(report, null, 2)}\n`;
}

export function formatRulesText(rules: readonly Rule[]): string {
  const width = Math.max(0, ...rules.map((rule) => rule.id.length));
  return `${rules.map((rule) => `${rule.id.padEnd(width)}  ${rule.severity.padEnd(7)}  ${rule.title}`).join('\n')}\n`;
}

export function formatRulesJson(rules: readonly Rule[]): string {
  const data = rules.map(({ id, title, severity, rationale }) => ({ id, title, severity, rationale }));
  return `${JSON.stringify(data, null, 2)}\n`;
}

/** Renders docs/rules.md. A test keeps the committed file in sync with this output. */
export function formatRulesMarkdown(rules: readonly Rule[]): string {
  const lines = [
    '# Rules',
    '',
    '<!-- Generated by `npm run docs`. Do not edit by hand. -->',
    '',
    '`error` rules decide the exit code. `warning` rules only lower the score.',
    '',
    '| Rule | Severity | Checks |',
    '| --- | --- | --- |',
    ...rules.map((rule) => `| [\`${rule.id}\`](#${rule.id}) | ${rule.severity} | ${rule.title} |`),
  ];
  for (const rule of rules) {
    lines.push('', `## ${rule.id}`, '', `**${rule.title}** · ${rule.severity}`, '', rule.rationale);
  }
  return `${lines.join('\n')}\n`;
}
